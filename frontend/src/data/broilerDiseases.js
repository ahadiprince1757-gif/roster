/** Sorted by severity for default display (Critical first) */
export const broilerDiseasesSorted = [...broilerDiseases].sort(
  (a, b) => b.severityScore - a.severityScore
);

/** Map for O(1) lookup by disease id */
export const broilerDiseaseMap = Object.fromEntries(
  broilerDiseases.map((d) => [d.id, d])
);

/** Filter by category */
export function getDiseasesByCategory(category) {
  return broilerDiseases.filter((d) => d.category === category);
}

/** Filter by severity */
export function getDiseasesBySeverity(severity) {
  return broilerDiseases.filter((d) => d.severity === severity);
}

/** Full-text search across name, symptoms, broilerSigns, and keywords */
export function searchDiseases(query) {
  const q = query.toLowerCase().trim();
  if (!q) return broilerDiseasesSorted;
  return broilerDiseasesSorted.filter((d) => {
    const fields = [
      d.name,
      ...d.symptoms,
      ...(d.broilerSigns || []),
      ...(d.keywords || []),
      d.category,
    ].join(' ').toLowerCase();
    return fields.includes(q);
  });
}

